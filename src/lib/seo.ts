import type { Metadata } from 'next';
import { getTranslations } from 'next-intl/server';
import { profile } from '@/content/profile';
import { contactInfo } from '@/content/contact';
import { coreTechnologies } from '@/content/core-technologies';
import { routing } from '@/i18n/routing';
import { getSectionHref } from '@/lib/navigation';
import type { SectionId } from '@/interfaces/navigation.interface';

export const SITE_URL = 'https://www.lautarojson.dev';

const OG_LOCALES: Record<string, string> = {
  en: 'en_US',
  es: 'es_AR',
};

// Absolute URL of a section for a given locale. Home lives at `/{locale}`
// (no trailing slash), the rest at `/{locale}/{section}`.
export const buildSectionUrl = (locale: string, section: SectionId): string => {
  const href = getSectionHref(section);
  return `${SITE_URL}/${locale}${href === '/' ? '' : href}`;
};

export const buildLanguageAlternates = (
  section: SectionId
): Record<string, string> => {
  return {
    ...Object.fromEntries(
      routing.locales.map((locale) => [
        locale,
        buildSectionUrl(locale, section),
      ])
    ),
    'x-default': buildSectionUrl(routing.defaultLocale, section),
  };
};

interface IBuildMetadataParams {
  locale: string;
  section: SectionId;
}

export const buildMetadata = async ({
  locale,
  section,
}: IBuildMetadataParams): Promise<Metadata> => {
  const t = await getTranslations({ locale, namespace: 'metadata' });
  const title = t(`pages.${section}.title`);
  const description = t(`pages.${section}.description`);
  const url = buildSectionUrl(locale, section);
  // The image is generated by `app/[locale]/opengraph-image.tsx`. Next.js only
  // attaches file-based OG images to the segment that owns the file, so nested
  // section routes reference it explicitly.
  const ogImage = {
    url: `${SITE_URL}/${locale}/opengraph-image`,
    width: 1200,
    height: 630,
    alt: t('ogImageAlt'),
  };

  return {
    title,
    description,
    alternates: {
      canonical: url,
      languages: buildLanguageAlternates(section),
    },
    openGraph: {
      type: section === 'home' ? 'profile' : 'website',
      locale: OG_LOCALES[locale] ?? OG_LOCALES.en,
      alternateLocale: routing.locales
        .filter((l) => l !== locale)
        .map((l) => OG_LOCALES[l]),
      url,
      siteName: t('siteName'),
      title,
      description,
      images: [ogImage],
    },
    twitter: {
      card: 'summary_large_image',
      title,
      description,
      images: [ogImage],
    },
    robots: {
      index: true,
      follow: true,
    },
  };
};

interface IBuildPersonJsonLdParams {
  locale: string;
}

export const buildPersonJsonLd = async ({
  locale,
}: IBuildPersonJsonLdParams) => {
  const t = await getTranslations({ locale, namespace: 'metadata' });
  const sameAs = contactInfo.socialLinks
    .filter((link) => link.platform !== 'email' && link.url)
    .map((link) => link.url);

  return {
    '@context': 'https://schema.org',
    '@type': 'Person',
    name: profile.name,
    jobTitle: t('jobTitle'),
    url: buildSectionUrl(locale, 'home'),
    email: `mailto:${contactInfo.email}`,
    address: {
      '@type': 'PostalAddress',
      addressLocality: 'Buenos Aires',
      addressCountry: 'AR',
    },
    alumniOf: {
      '@type': 'CollegeOrUniversity',
      name: 'Universidad Tecnológica Nacional',
    },
    knowsAbout: coreTechnologies.map((technology) => technology.name),
    sameAs,
  };
};
